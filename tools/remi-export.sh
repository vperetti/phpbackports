#!/usr/bin/env bash
#
# remi-export.sh — export Remi Collet's security-backport branch for one PHP
# 7.x release as a single patch against the official php.net tarball.
#
# Source: https://github.com/remicollet/php-src-security (PHP License 3.01)
#
# Usage: tools/remi-export.sh <version> <remi-branch> <commit> <out.patch>
#   e.g. tools/remi-export.sh 7.3.33 PHP-7.3-security-backports 399a749a5cb0... patches/remi/php-7.3-remi-security-backports.patch
#
# Needs: git, curl, tar, re2c (2.2 was used for the committed patches).
#
# Why not just "git diff tag branch": the tarball ships files generated by
# re2c (date parser, URL scanner, PDO SQL parser) that the git tree does not
# regenerate. Remi changed their .re sources, so the generated .c files are
# regenerated here and included in the patch; builds (Linux or Windows/VC15)
# then do not need re2c.

set -euo pipefail
V="$1"; BR="$2"; COMMIT="$3"; OUT="$(realpath -m "$4")"
RE2C="${RE2C:-re2c}"
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT

# 1. Remi's branch vs the official tag, as a git diff
git -C "$W" init -q src
git -C "$W/src" fetch -q --depth=1 https://github.com/php/php-src.git "refs/tags/php-$V:refs/tags/php-$V"
git -C "$W/src" fetch -q --depth=1 https://github.com/remicollet/php-src-security.git "$BR"
got=$(git -C "$W/src" rev-parse FETCH_HEAD)
[ "${got#"$COMMIT"}" != "$got" ] || { echo "branch head is $got, expected $COMMIT" >&2; exit 1; }
git -C "$W/src" diff --binary "php-$V" "$got" > "$W/remi.diff"

# 2. Apply it to the official tarball and regenerate the re2c outputs
curl -sfL -o "$W/php.tar.bz2" "https://www.php.net/distributions/php-$V.tar.bz2"
mkdir "$W/t"; tar xjf "$W/php.tar.bz2" -C "$W/t" --strip-components=1
cd "$W/t"
git init -q .
echo '* -ident -text -eol' > .git/info/attributes   # keep $Id$ and line endings as shipped
git add -A -f . && git -c user.name=export -c user.email=export@localhost commit -q -m tarball
git apply -p1 --whitespace=nowarn "$W/remi.diff"
(cd ext/date/lib && "$RE2C" --no-generation-date -d -b parse_date.re > parse_date.c \
                 && "$RE2C" --no-generation-date -d -b parse_iso_intervals.re > parse_iso_intervals.c)
"$RE2C" --no-generation-date -b -o ext/standard/url_scanner_ex.c ext/standard/url_scanner_ex.re
"$RE2C" --no-generation-date -o ext/pdo/pdo_sql_parser.c ext/pdo/pdo_sql_parser.re 2>/dev/null

# 3. One patch, tarball -> patched tree (binary test fixtures included)
git add -A -f .
{ echo "PHP $V + Remi Collet security backports"
  echo "source: https://github.com/remicollet/php-src-security/tree/$BR"
  echo "commit: $got"
  echo "apply : cd php-$V && git apply -p1 <this file>"
  echo
  git diff --cached --binary; } > "$OUT"
echo "$OUT: $(grep -c '^diff --git' "$OUT") files"
